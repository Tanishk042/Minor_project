package org.forestear.node.decision

import java.util.Locale

data class WindowScores(
    val m2: Double = 0.0,
    val m3: Double = 0.0,
    val m4: Double = 0.0,
    val m7: Double = 0.0,
    val m6Z: Double = 0.0,
    val m5Rain: Double = 0.0,
    val m5Wind: Double = 0.0,
    val m5Thunder: Double = 0.0,
    val m9: Map<String, Double> = emptyMap(),
    val rmsDb: Double = -100.0,
)

data class Decision(
    val cls: String,
    val severity: String?,
    val confidence: Double,
    val fired: Boolean = false,
    val suppressedBy: String? = null,
    val escalated: Boolean = false,
    val kOfN: String = "",
    val cooldownActive: Boolean = false,
)

/**
 * Kotlin port of forestear/edge_agent/decision.py.
 *
 * The Python implementation is the contract; golden vectors are generated by
 * running that code over scripted score sequences (see
 * android/tools/export_android_assets.py). Keep the two in sync.
 */
class DecisionEngine(
    @Volatile var config: DecisionConfig,
) {
    private data class Detection(val t: Double, val conf: Double)

    private val detections = mutableMapOf<String, ArrayDeque<Detection>>()
    private val lastFired = mutableMapOf<String, Double>()
    private val chainsawTimes = mutableListOf<Double>()
    @Volatile var chainsawEscalated: Boolean = false
        private set

    private fun ring(cls: String): ArrayDeque<Detection> =
        detections.getOrPut(cls) { ArrayDeque() }

    fun update(s: WindowScores, t: Double): List<Decision> {
        val out = mutableListOf<Decision>()
        val weather = maxOf(s.m5Rain, s.m5Wind, s.m5Thunder)
        val vetoActive = config.vetoEnable && weather >= config.vetoWeatherProb

        val classes = linkedMapOf(
            "chainsaw" to Pair(s.m9["chainsaw"] ?: 0.0, s.m3),
            "gunshot" to Pair(s.m9["gunshot"] ?: 0.0, s.m2),
            "vehicle" to Pair(s.m9["vehicle"] ?: 0.0, s.m4),
            "human" to Pair(s.m9["human"] ?: 0.0, s.m7),
        )
        for ((cls, pair) in classes) {
            val (m9p, modelP) = pair
            val thr = config.thresholds[cls] ?: continue
            val detected = m9p >= thr || modelP >= thr + 0.15
            val conf = maxOf(m9p, modelP)
            if (detected) {
                val r = ring(cls)
                r.addLast(Detection(t, conf))
                while (r.size > 64) r.removeFirst()
                if (cls == "chainsaw") {
                    chainsawTimes.add(t)
                    chainsawTimes.removeAll { t - it > config.chainsawSustain.n }
                    if (chainsawTimes.size < config.chainsawSustain.k) {
                        chainsawEscalated = false
                    }
                }
            }
        }

        val anomalyThr = config.thresholds["anomaly"] ?: 0.7
        if (s.m6Z >= anomalyThr && s.rmsDb > 35.0) {
            val r = ring("anomaly")
            r.addLast(Detection(t, s.m6Z))
            while (r.size > 64) r.removeFirst()
        }

        for (cls in listOf("chainsaw", "gunshot", "vehicle", "human", "anomaly")) {
            decideClass(cls, t, vetoActive, s)?.let { out.add(it) }
        }
        return out
    }

    private fun decideClass(
        cls: String,
        t: Double,
        vetoActive: Boolean,
        s: WindowScores,
    ): Decision? {
        val ring = detections[cls] ?: return null
        if (ring.isEmpty()) return null
        val p = config.persistence[cls] ?: return null
        val k = p.k
        val n = p.n
        val windowS = n * 0.5 + 0.1
        val recent = ring.filter { t - it.t <= windowS }
        val conf = recent.lastOrNull()?.conf ?: ring.last().conf

        val sustainedNow = cls == "chainsaw" &&
            chainsawTimes.size >= config.chainsawSustain.k
        val cooldown = config.cooldownS[cls] ?: 0.0
        val last = lastFired[cls]
        if (last != null && t - last < cooldown &&
            !(sustainedNow && !chainsawEscalated)
        ) {
            return null
        }

        var fired = false
        val nHit = recent.size
        if (cls == "gunshot") {
            val high = p.highConf ?: 0.85
            val thr = config.thresholds["gunshot"] ?: 0.6
            if (conf >= high && nHit >= 1) {
                fired = true
            } else if (nHit >= 2 && conf >= thr * 0.7) {
                fired = true
            }
        } else {
            fired = nHit >= k
        }

        if (fired && cls == "gunshot" && vetoActive) {
            if (conf < config.vetoGunshotConf) {
                val weather = maxOf(s.m5Rain, s.m5Wind, s.m5Thunder)
                val reason = String.format(
                    Locale.US, "weather_veto(M5 weather=%.2f)", weather
                )
                return Decision(
                    cls = cls, severity = null, confidence = conf,
                    fired = false, suppressedBy = reason
                )
            }
        }
        if (!fired) return null

        var sev = config.severity[cls] ?: "INFO"
        var escalated = false
        if (cls == "chainsaw" && chainsawTimes.size >= config.chainsawSustain.k) {
            sev = "CRITICAL"
            escalated = true
            chainsawEscalated = true
        }
        lastFired[cls] = t
        return Decision(
            cls = cls, severity = sev, confidence = conf, fired = true,
            escalated = escalated,
            kOfN = "$nHit/${if (cls == "gunshot") 3 else n}"
        )
    }
}
