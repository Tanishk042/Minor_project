package org.forestear.node

import org.forestear.node.config.AppConfig
import org.forestear.node.decision.DecisionEngine
import org.forestear.node.decision.WindowScores
import org.forestear.node.util.ClasspathAssetSource
import org.json.JSONArray
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Decision logic is safety-relevant: persistence, cooldowns, weather veto and
 * chainsaw escalation must behave exactly like the Python reference. The golden
 * file is generated by running `edge_agent/decision.py` over scripted scores.
 */
class DecisionEngineTest {
    private val source = ClasspathAssetSource()
    private val config = AppConfig.load(source)

    @Test
    fun decisionEngineMatchesPythonGoldenVectors() {
        val vectors = JSONArray(source.readText("golden/decision_vectors.json"))
        for (i in 0 until vectors.length()) {
            val vector = vectors.getJSONObject(i)
            val name = vector.getString("name")
            val engine = DecisionEngine(config.decision)
            val steps = vector.getJSONArray("steps")
            for (s in 0 until steps.length()) {
                val step = steps.getJSONObject(s)
                val scores = toScores(step.getJSONObject("in"))
                val t = step.optDouble("t", s.toDouble())
                val actual = engine.update(scores, t)
                val expected = step.getJSONArray("out")
                assertEquals("$name step $s decision count", expected.length(), actual.size)
                for (d in 0 until expected.length()) {
                    val e = expected.getJSONObject(d)
                    val a = actual[d]
                    assertEquals("$name step $s cls", e.getString("cls"), a.cls)
                    assertEquals(
                        "$name step $s severity",
                        if (e.isNull("severity")) null else e.getString("severity"),
                        a.severity,
                    )
                    assertEquals(
                        "$name step $s confidence",
                        e.getDouble("confidence"),
                        a.confidence,
                        1e-9,
                    )
                    assertEquals("$name step $s fired", e.getBoolean("fired"), a.fired)
                    assertEquals(
                        "$name step $s suppressed_by",
                        if (e.isNull("suppressed_by")) null else e.getString("suppressed_by"),
                        a.suppressedBy,
                    )
                    assertEquals(
                        "$name step $s escalated",
                        e.optBoolean("escalated", false),
                        a.escalated,
                    )
                    assertEquals(
                        "$name step $s k_of_n",
                        e.optString("k_of_n", ""),
                        a.kOfN,
                    )
                }
            }
        }
    }

    @Test
    fun gunshotVetoDoesNotSwallowConfidentGunshot() {
        // Rain is above the weather-veto probability, but a high-confidence M2
        // detection must still fire: a thunderstorm must not veto gunshots.
        val engine = DecisionEngine(config.decision)
        val scores = WindowScores(
            m2 = 0.95,
            m9 = mapOf("gunshot" to 0.95),
            m5Rain = 0.99,
            m5Thunder = 0.4,
            rmsDb = -20.0,
        )
        val decisions = engine.update(scores, 0.0)
        val gunshot = decisions.firstOrNull { it.cls == "gunshot" }
        assertNotNull("gunshot decision missing", gunshot)
        assertTrue("gunshot must fire despite rain", gunshot!!.fired)
        assertEquals("CRITICAL", gunshot.severity)
        assertNull(gunshot.suppressedBy)
    }

    @Test
    fun lowConfidenceGunshotIsVetoedByRain() {
        val engine = DecisionEngine(config.decision)
        val scores = WindowScores(
            m2 = 0.62,
            m9 = mapOf("gunshot" to 0.62),
            m5Rain = 0.99,
            rmsDb = -25.0,
        )
        // Gunshot needs two detections inside the persistence window before it
        // is eligible to fire (the reference engine behaves the same way), so
        // the first hop emits no decision at all.
        assertTrue(engine.update(scores, 0.0).isEmpty())
        val decisions = engine.update(scores, 0.5)
        val gunshot = decisions.firstOrNull { it.cls == "gunshot" }
        assertNotNull("gunshot decision missing", gunshot)
        assertTrue("low-confidence gunshot should be suppressed", !gunshot!!.fired)
        assertTrue(
            "expected weather_veto, got ${gunshot.suppressedBy}",
            gunshot.suppressedBy?.startsWith("weather_veto") == true,
        )
    }

    private fun toScores(o: JSONObject): WindowScores {
        val m9 = mutableMapOf<String, Double>()
        o.optJSONObject("m9")?.let { m ->
            for (key in m.keys()) m9[key] = m.getDouble(key)
        }
        return WindowScores(
            m2 = o.optDouble("m2", 0.0),
            m3 = o.optDouble("m3", 0.0),
            m4 = o.optDouble("m4", 0.0),
            m7 = o.optDouble("m7", 0.0),
            m6Z = o.optDouble("m6_z", 0.0),
            m5Rain = o.optDouble("m5_rain", 0.0),
            m5Wind = o.optDouble("m5_wind", 0.0),
            m5Thunder = o.optDouble("m5_thunder", 0.0),
            m9 = m9,
            rmsDb = o.optDouble("rms_db", -100.0),
        )
    }
}
